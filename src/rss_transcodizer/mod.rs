use std::collections::BTreeMap;

use eyre::eyre;
use log::debug;
use reqwest::Url;
use rss::extension::itunes::ITunesCategory;
use rss::Channel;
use rss::{Enclosure, Item};

use crate::configs::{conf, AudioCodec, Conf, ConfName};
use crate::episode_identity;
use crate::provider::duration::parse_duration;
// the enclosure `length` and the served Content-Length share the one
// byte-count formula, owned by the transcoder's media-sizing module
// (issue #184, ADR-0002)
use crate::transcoder::media_sizing::streamable_bytes;

pub fn inject_vod2pod_customizations(
    rss_body: String,
    transcode_service_url: Option<Url>,
    artwork_service_url: Option<Url>,
) -> eyre::Result<String> {
    let mut injected_feed = Channel::read_from(rss_body.as_bytes())?;
    injected_feed.set_generator(Some("generated by vod2pod-rss".to_string()));
    if let Some(ref mut itunes) = injected_feed.itunes_ext {
        let mut default_category = ITunesCategory::default();
        default_category.set_text("Technology");
        itunes.set_categories(vec![default_category]);
    }
    let mut namespaces = BTreeMap::new();
    namespaces.insert(
        "rss".to_string(),
        "http://www.itunes.com/dtds/podcast-1.0.dtd".to_string(),
    );
    namespaces.insert(
        "itunes".to_string(),
        "http://www.itunes.com/dtds/podcast-1.0.dtd".to_string(),
    );
    namespaces.insert(
        "content".to_string(),
        "http://purl.org/rss/1.0/modules/content/".to_string(),
    );
    injected_feed.set_namespaces(namespaces);
    injected_feed.set_language("en-US".to_string());
    let bitrate: u64 = conf()
        .get(ConfName::Mp3Bitrate)
        .unwrap()
        .parse()
        .expect("MP3_BITRATE must be a number");
    let codec: AudioCodec = conf().get(ConfName::AudioCodec).unwrap().into();
    let ext = format!(".{}", codec.get_extension_str());
    injected_feed
        .items_mut()
        .iter_mut()
        .try_for_each(|item| -> eyre::Result<_> {
            // the shownotes picture keeps the upstream still: an HTML <img>
            // is shown whole, so it has nothing to crop away
            let description = get_description(item);
            item.set_description(description);
            // Square Episode Artwork (docs/adr/0004): a YouTube still served
            // as-is gets cropped by the player. Only provider-set artwork is
            // rewritten — inventing one would turn a show-cover fallback into
            // a broken image.
            if let (Some(artwork_service_url), Some(video_id)) =
                (artwork_service_url.as_ref(), youtube_video_id(item))
            {
                let mut artwork_url = artwork_service_url.clone();
                artwork_url
                    .query_pairs_mut()
                    .append_pair("id", video_id.as_str());
                if let Some(itunes_ext) = item.itunes_ext.as_mut() {
                    if itunes_ext.image().is_some() {
                        itunes_ext.set_image(Some(artwork_url.to_string()));
                    }
                }
            }
            if let Some(mut transcode_service_url) = transcode_service_url.clone() {
                let duration_secs = &item
                    .itunes_ext()
                    .and_then(|i| Some(parse_duration(i.duration()?).ok()?.as_secs()))
                    .ok_or(eyre!(
                        "no duration found or could not parse {:?}",
                        item.itunes_ext()
                    ))?;
                // the link is mandatory: the enclosure itself points at it
                let source_link = item
                    .link()
                    .ok_or(eyre!("not url found in item"))?
                    .to_string();
                // Deterministic Enclosure URL: the uuid is derived by the
                // Episode identity module (docs/adr/0002), so the injected
                // body — and the ETag the server derives from it — is stable
                // across serves and identical across subscribers.
                let generation_uuid =
                    episode_identity::enclosure_uuid(item.guid().map(|g| g.value()), &source_link)
                        .to_string();
                transcode_service_url
                    .query_pairs_mut()
                    .append_pair("bitrate", bitrate.to_string().as_str())
                    .append_pair("uuid", generation_uuid.as_str())
                    .append_pair("duration", duration_secs.to_string().as_str())
                    .append_pair("url", source_link.as_str())
                    .append_pair("ext", ext.as_str()); //this should allways be last, some players refuse to play urls not ending in .mp3

                let enclosure = Enclosure {
                    length: streamable_bytes(*duration_secs, bitrate).to_string(),
                    url: transcode_service_url.to_string(),
                    mime_type: "audio/mpeg".to_string(),
                };

                debug!(
                    "setting enclosure to: \nlength: {}, url: {}, mime_type: {}",
                    enclosure.length, enclosure.url, enclosure.mime_type
                );
                item.set_enclosure(Some(enclosure));
            }
            Ok(())
        })?;

    Ok(injected_feed.to_string())
}

/// The video id of a YouTube Episode — the only Episodes this service can
/// compose square artwork for. Anything else (PeerTube, Twitch, a generic
/// feed) keeps the artwork its provider set. The guid is the fallback because
/// ADR 0002 freezes it as the watch URL for every YouTube Episode, which is
/// what covers the atom rung's `/shorts/<id>` links.
fn youtube_video_id(item: &Item) -> Option<String> {
    [item.link(), item.guid().map(|guid| guid.value())]
        .into_iter()
        .flatten()
        .find_map(video_id_from_watch_url)
}

fn video_id_from_watch_url(link: &str) -> Option<String> {
    let url = Url::parse(link).ok()?;
    if !matches!(
        url.host_str()?,
        "youtube.com" | "www.youtube.com" | "m.youtube.com"
    ) {
        return None;
    }
    let video_id = url
        .query_pairs()
        .find(|(key, _)| key == "v")
        .map(|(_, value)| value.into_owned())?;
    crate::artwork::is_video_id(&video_id).then_some(video_id)
}

fn get_description(item: &Item) -> String {
    const FOOTER: &str = concat!(
        "<br><br>generated by vod2pod-rss ",
        env!("CARGO_PKG_VERSION"),
        " made by Mattia Di Eleuterio (<a href=\"https://github.com/madiele\">madiele</a>). Check out the <a href=\"https://github.com/madiele/vod2pod-rss\">GitHub repository</a>."
    );
    let description = item.description().unwrap_or_default().replace("\n", "<br>");
    let url = item.link().unwrap_or_default();
    let img = item
        .itunes_ext()
        .and_then(|i| i.image())
        .unwrap_or_default();

    let original_link = format!(
        "<br><br><a href=\"{}\"><p>link to original</p><img src=\"{}\"></a>",
        url, img
    );
    format!("{}{}{}", description, original_link, FOOTER)
}

#[cfg(test)]
mod tests {
    use super::*;

    const TWO_ITEM_RSS: &str = r#"<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:itunes="http://www.itunes.com/dtds/podcast-1.0.dtd">
<channel>
<title>t</title>
<link>https://example.com</link>
<description>d</description>
<item>
  <title>episode one</title>
  <link>https://www.youtube.com/watch?v=abc</link>
  <guid>https://www.youtube.com/watch?v=abc</guid>
  <itunes:duration>00:10:00</itunes:duration>
  <description>about one</description>
  <itunes:image href="https://example.com/one.jpg"/>
</item>
<item>
  <title>episode two</title>
  <link>https://www.youtube.com/watch?v=def</link>
  <guid>https://www.youtube.com/watch?v=def</guid>
  <itunes:duration>00:20:00</itunes:duration>
  <description>about two</description>
  <itunes:image href="https://example.com/two.jpg"/>
</item>
</channel>
</rss>"#;

    fn inject_default() -> rss::Channel {
        let body = inject_vod2pod_customizations(
            TWO_ITEM_RSS.to_string(),
            Some(Url::parse("http://127.0.0.1:8080/transcode_media/to.mp3").unwrap()),
            None,
        )
        .unwrap();
        rss::Channel::read_from(body.as_bytes()).unwrap()
    }

    fn artwork_base() -> Url {
        Url::parse("http://127.0.0.1:8080/artwork").unwrap()
    }

    fn inject_with_artwork(rss_body: &str) -> rss::Channel {
        let body = inject_vod2pod_customizations(rss_body.to_string(), None, Some(artwork_base()))
            .unwrap();
        rss::Channel::read_from(body.as_bytes()).unwrap()
    }

    fn item_images(channel: &rss::Channel) -> Vec<Option<String>> {
        channel
            .items
            .iter()
            .map(|i| {
                i.itunes_ext()
                    .and_then(|ext| ext.image())
                    .map(str::to_string)
            })
            .collect()
    }

    /// Apple Podcasts crops anything that is not square, so a YouTube still
    /// must be replaced by this service's composed square — pointing at the
    /// video id, not at any URL the feed happened to carry.
    #[test]
    fn test_youtube_episode_artwork_points_at_the_composed_square() {
        let channel = inject_with_artwork(TWO_ITEM_RSS);
        assert_eq!(
            item_images(&channel),
            vec![
                Some("http://127.0.0.1:8080/artwork?id=abc".to_string()),
                Some("http://127.0.0.1:8080/artwork?id=def".to_string()),
            ]
        );
    }

    /// PeerTube, Twitch and generic feeds are not ours to compose: their
    /// artwork arrives already shaped for the player that supplied it.
    #[test]
    fn test_foreign_episode_artwork_is_left_untouched() {
        let foreign = TWO_ITEM_RSS
            .replace(
                "https://www.youtube.com/watch?v=abc",
                "https://peertube.example/w/abc",
            )
            .replace(
                "https://www.youtube.com/watch?v=def",
                "https://peertube.example/w/def",
            );
        let channel = inject_with_artwork(&foreign);
        assert_eq!(
            item_images(&channel),
            vec![
                Some("https://example.com/one.jpg".to_string()),
                Some("https://example.com/two.jpg".to_string()),
            ]
        );
    }

    /// A video whose provider set no artwork keeps none: the player then shows
    /// the show cover, which is square already. Inventing an artwork URL here
    /// would hand the listener a broken square instead.
    #[test]
    fn test_an_episode_without_artwork_gets_none() {
        let channel = inject_with_artwork(
            &TWO_ITEM_RSS.replace("<itunes:image href=\"https://example.com/one.jpg\"/>", ""),
        );
        assert_eq!(item_images(&channel)[0], None);
        assert!(
            item_images(&channel)[1].is_some(),
            "the second item is untouched"
        );
    }

    /// The kill switch: with no artwork service URL the upstream image is
    /// served exactly as before this feature existed.
    #[test]
    fn test_artwork_is_untouched_when_the_composer_is_off() {
        let channel = inject_default();
        assert_eq!(
            item_images(&channel),
            vec![
                Some("https://example.com/one.jpg".to_string()),
                Some("https://example.com/two.jpg".to_string()),
            ]
        );
    }

    #[test]
    fn test_video_id_from_a_watch_link() {
        assert_eq!(
            video_id_from_watch_url("https://www.youtube.com/watch?v=dQw4w9WgXcQ"),
            Some("dQw4w9WgXcQ".to_string())
        );
        for not_ours in [
            "https://peertube.example/w/abc",
            "https://www.youtube.com/channel/UC123",
            "https://www.youtube.com/watch?v=../etc",
            "not a url",
        ] {
            assert_eq!(video_id_from_watch_url(not_ours), None, "{not_ours:?}");
        }
    }

    /// The atom rung links Shorts as `/shorts/<id>`, so the id has to come
    /// from the guid — ADR 0002 freezes it as the watch URL — or every Shorts
    /// episode keeps the 16:9 still the player crops.
    #[test]
    fn test_shorts_episode_takes_its_id_from_the_guid() {
        let shorts = TWO_ITEM_RSS
            .replace(
                "<link>https://www.youtube.com/watch?v=abc</link>",
                "<link>https://www.youtube.com/shorts/abc</link>",
            )
            .replace(
                "<link>https://www.youtube.com/watch?v=def</link>",
                "<link>https://www.youtube.com/shorts/def</link>",
            );
        let channel = inject_with_artwork(&shorts);
        assert_eq!(
            item_images(&channel),
            vec![
                Some("http://127.0.0.1:8080/artwork?id=abc".to_string()),
                Some("http://127.0.0.1:8080/artwork?id=def".to_string()),
            ]
        );
    }

    /// The whole injected body must be byte-identical across serves of the
    /// same cached feed: the server derives its ETag from this body, so any
    /// per-serve variation defeats conditional GET (304) entirely.
    #[test]
    fn test_injection_is_deterministic() {
        let first = inject_vod2pod_customizations(
            TWO_ITEM_RSS.to_string(),
            Some(Url::parse("http://127.0.0.1:8080/transcode_media/to.mp3").unwrap()),
            Some(artwork_base()),
        )
        .unwrap();
        let second = inject_vod2pod_customizations(
            TWO_ITEM_RSS.to_string(),
            Some(Url::parse("http://127.0.0.1:8080/transcode_media/to.mp3").unwrap()),
            Some(artwork_base()),
        )
        .unwrap();
        assert_eq!(first, second);
    }

    #[test]
    fn test_enclosure_uuid_differs_per_episode() {
        let channel = inject_default();
        let urls: Vec<String> = channel
            .items
            .iter()
            .map(|i| i.enclosure().unwrap().url().to_string())
            .collect();
        assert_ne!(
            urls[0], urls[1],
            "two episodes must not share an enclosure url"
        );
    }

    /// The injected uuid is the Episode identity module's derivation, byte
    /// for byte: any regression at the injection site (a fresh uuid per
    /// serve, a different seed) breaks the body's stability and fails here.
    /// The v5-of(guid) scheme itself is pinned in the identity module.
    #[test]
    fn test_enclosure_uuid_is_v5_of_episode_guid() {
        let channel = inject_default();
        let expected = episode_identity::enclosure_uuid(
            Some("https://www.youtube.com/watch?v=abc"),
            "https://www.youtube.com/watch?v=abc",
        )
        .to_string();
        let url = channel.items[0].enclosure().unwrap().url().to_string();
        assert!(
            url.contains(&format!("uuid={expected}")),
            "enclosure url must embed uuid v5 of the episode guid, got: {url}"
        );
    }

    #[test]
    fn test_enclosure_length_matches_served_bytes() {
        // the server streams duration * bitrate * 1000 / 8 bytes (192 kbps
        // default): the enclosure length must be the same number, not the old
        // bitrate * 1024 * seconds formula
        let channel = inject_default();
        for item in &channel.items {
            let duration = item.itunes_ext().unwrap().duration().unwrap();
            let secs = parse_duration(duration).unwrap().as_secs();
            let expected = secs * 192 * 1000 / 8;
            assert_eq!(
                item.enclosure().unwrap().length(),
                expected.to_string(),
                "enclosure length must equal the byte count the server serves"
            );
        }
    }
}
